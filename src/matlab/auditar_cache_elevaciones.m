function summary=auditar_cache_elevaciones(cacheFile,nodeFile,folder)
% Comprueba correspondencia, NO certifica datum ni que Alt_m sea terreno.
S=load(cacheFile,'lat','lon','Alt_m');
assert(isfield(S,'lat') && isfield(S,'lon') && isfield(S,'Alt_m'), ...
    'Trazable:Cache','La cache debe conservar coordenadas y cotas.');
lat=S.lat(:);lon=S.lon(:);alt=S.Alt_m(:);
assert(numel(lat)==numel(lon) && numel(lat)==numel(alt), ...
    'Trazable:Cache','Vectores incompatibles.');
assert(all(isfinite(lat)&isfinite(lon)&isfinite(alt)), ...
    'Trazable:Cache','Cache con valores ausentes.');
T=readtable(nodeFile,'TextType','string');n=height(T);nearest=zeros(n,1);distance=nearest;
for k=1:n
    d=hypot(deg2rad(lon-T.Longitude(k))*6371000*cosd(T.Latitude(k)), ...
        deg2rad(lat-T.Latitude(k))*6371000);
    [distance(k),nearest(k)]=min(d);
end
matched=distance<=0.5;newalt=nan(n,1);newalt(matched)=alt(nearest(matched));
delta=newalt-T.Elevation_MSNM;
A=table(T.Node_ID,T.Latitude,T.Longitude,T.Elevation_MSNM,nearest,distance,newalt,delta,matched, ...
    'VariableNames',{'Node_ID','Latitude','Longitude','LegacyElevation_m','CacheIndex', ...
    'CacheDistance_m','CacheElevation_m','Delta_vs_legacy_m','CoordinateMatched'});
if ~isfolder(folder),mkdir(folder);end
writetable(A,fullfile(folder,'auditoria_cache_por_coordenada.csv'));
summary=struct('CacheSHA256',trazable_sha256(cacheFile),'CacheEntries',numel(lat), ...
    'Nodes',n,'CoordinateMatched',nnz(matched),'MaxMatchDistance_m',max(distance(matched)), ...
    'NodesDiffMoreThan1m',nnz(matched & abs(delta)>1), ...
    'MaxAbsoluteDelta_m',max(abs(delta(matched))), ...
    'VerticalDatumVerified',false,'GroundVersusAntennaAltitudeVerified',false);
fid=fopen(fullfile(folder,'resumen_cache.json'),'w','n','UTF-8');c=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(summary,'PrettyPrint',true));disp(summary);
end
