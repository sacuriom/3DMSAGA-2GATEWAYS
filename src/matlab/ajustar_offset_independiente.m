function coefficients = ajustar_offset_independiente(trainingCSV, campaignID, outputJSON)
% Ajuste por gateway SOLO en una campana declarada como entrenamiento.
% El CSV procede de intersecciones_por_gateway.csv del modelo fisico.
opts=detectImportOptions(trainingCSV);
opts=setvartype(opts,{'Gateway_ID','Campaign_ID','Model_Version','BaseModelSHA256','FrameKeys'},'string');
T=readtable(trainingCSV,opts);
assert(isscalar(unique(T.Campaign_ID)) && all(T.Campaign_ID==string(campaignID)), ...
    'Trazable:TrainingCampaign','Entrenamiento ambiguo o campana inconsistente.');
versions=unique(T.Model_Version);
assert(isscalar(versions) && ~startsWith(versions,"legacy"), ...
    'Trazable:TrainingModel','Calibrar solo un modelo fisico versionado, no el maximo heredado.');
fingerprint=unique(T.BaseModelSHA256);
assert(isscalar(fingerprint) && strlength(fingerprint)==64, ...
    'Trazable:TrainingFingerprint','Hay condiciones fisicas distintas o sin huella.');
assert(all(isfinite(T.PredictedRaw_dBm) & isfinite(T.MeasuredMedian_dBm)), ...
    'Trazable:TrainingMissing','Observaciones de entrenamiento ausentes.');
% Compensacion robusta de offset con pendiente fija: no comprime la dinamica.
ids=unique(T.Gateway_ID);g=struct('ID',{},'Slope',{},'Offset_dB',{},'N_nodes',{});
for k=1:numel(ids)
    s=T(T.Gateway_ID==ids(k),:);
    assert(height(s)>=20,'Trazable:TrainingSize', ...
        'Regla operativa: al menos 20 posiciones por gateway; no garantiza suficiencia estadistica.');
    g(k)=struct('ID',ids(k),'Slope',1,'Offset_dB',median(s.MeasuredMedian_dBm-s.PredictedRaw_dBm), ...
        'N_nodes',height(s));
end
keys=unique(split(strjoin(T.FrameKeys,';'),';'));keys=keys(strlength(keys)>0);
coefficients=struct('CampaignID',string(campaignID),'DeclaredRole',"training", ...
    'BaseModelVersion',versions,'BaseModelSHA256',fingerprint, ...
    'Policy',"per_gateway_median_offset_slope_fixed_1", ...
    'TrainingCSV',string(trainingCSV),'TrainingCSV_SHA256',trazable_sha256(trainingCSV), ...
    'TrainingFrameKeys',keys,'Gateways',g, ...
    'Scope',"Solo gateways fisicos; no transferir a otros candidatos sin verificar");
fid=fopen(outputJSON,'w','n','UTF-8');assert(fid>=0,'Trazable:Write','No se pudo guardar el ajuste.');
c=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(coefficients,'PrettyPrint',true));
end
